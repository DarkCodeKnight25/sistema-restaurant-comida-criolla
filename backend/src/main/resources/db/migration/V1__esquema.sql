-- Núcleo de restaurante: carta, mesas, pedidos por estación, cobros y cierre de caja.
-- Las horas se guardan en hora local de Lima.

create table estacion (
    id      bigint generated by default as identity primary key,
    codigo  varchar(20) not null unique,
    nombre  varchar(40) not null,
    color   varchar(7)  not null,
    orden   integer     not null
);

create table categoria (
    id      bigint generated by default as identity primary key,
    nombre  varchar(60) not null,
    orden   integer     not null
);

create table plato (
    id            bigint generated by default as identity primary key,
    categoria_id  bigint        not null references categoria(id),
    estacion_id   bigint        not null references estacion(id),
    nombre        varchar(80)   not null,
    descripcion   varchar(240),
    precio        numeric(8,2)  not null check (precio > 0),
    foto          varchar(120),
    disponible    boolean       not null default true,
    activo        boolean       not null default true,
    orden         integer       not null default 0
);

create table mesa (
    id         bigint generated by default as identity primary key,
    numero     integer     not null unique,
    token      varchar(24) not null unique,
    capacidad  integer     not null,
    zona       varchar(30) not null
);

-- Una atención es la visita de un grupo a una mesa: desde el primer pedido hasta que paga.
create table atencion (
    id          bigint generated by default as identity primary key,
    mesa_id     bigint      not null references mesa(id),
    estado      varchar(12) not null,
    abierta_en  timestamp   not null,
    cuenta_en   timestamp,
    cerrada_en  timestamp
);
create index ix_atencion_mesa_estado on atencion(mesa_id, estado);

create table pedido (
    id               bigint generated by default as identity primary key,
    codigo           varchar(10)   not null unique,
    fecha            date          not null,
    numero           integer       not null,
    tipo             varchar(10)   not null,
    atencion_id      bigint        references atencion(id),
    cliente_nombre   varchar(80),
    cliente_celular  varchar(9),
    direccion        varchar(160),
    referencia       varchar(160),
    estado           varchar(16)   not null,
    nota             varchar(240),
    total            numeric(10,2) not null,
    pagado           boolean       not null default false,
    creado_en        timestamp     not null,
    actualizado_en   timestamp     not null,
    unique (fecha, numero)
);
create index ix_pedido_fecha on pedido(fecha);

create table item_pedido (
    id              bigint generated by default as identity primary key,
    pedido_id       bigint        not null references pedido(id) on delete cascade,
    plato_id        bigint        not null references plato(id),
    estacion_id     bigint        not null references estacion(id),
    nombre          varchar(80)   not null,
    precio_unit     numeric(8,2)  not null,
    cantidad        integer       not null check (cantidad between 1 and 30),
    nota            varchar(120),
    estado          varchar(16)   not null,
    actualizado_en  timestamp     not null
);
create index ix_item_estado on item_pedido(estacion_id, estado);

create table pago (
    id           bigint generated by default as identity primary key,
    atencion_id  bigint        references atencion(id),
    pedido_id    bigint        references pedido(id),
    medio        varchar(10)   not null,
    monto        numeric(10,2) not null check (monto > 0),
    recibido     numeric(10,2),
    vuelto       numeric(10,2),
    cobrado_por  varchar(80)   not null,
    creado_en    timestamp     not null,
    check (atencion_id is not null or pedido_id is not null)
);
create index ix_pago_creado on pago(creado_en);

create table cierre_caja (
    id                bigint generated by default as identity primary key,
    fecha             date          not null unique,
    total_efectivo    numeric(10,2) not null,
    total_yape        numeric(10,2) not null,
    total_plin        numeric(10,2) not null,
    total_tarjeta     numeric(10,2) not null,
    efectivo_contado  numeric(10,2) not null,
    diferencia        numeric(10,2) not null,
    tickets           integer       not null,
    cerrado_por       varchar(80)   not null,
    cerrado_en        timestamp     not null
);

create table usuario (
    id             bigint generated by default as identity primary key,
    email          varchar(120) not null unique,
    nombre         varchar(80)  not null,
    password_hash  varchar(100) not null,
    rol            varchar(10)  not null
);

-- Correlativo diario de pedidos (#001, #002...). Se bloquea la fila del día al numerar.
create table contador_dia (
    fecha   date    primary key,
    ultimo  integer not null
);
